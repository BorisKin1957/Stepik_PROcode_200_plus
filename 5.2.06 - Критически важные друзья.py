'''
Задача: найти "критически важных" друзей — тех, у кого есть хотя бы один нужный номер,
которого нет ни у кого другого.

Алгоритм:
1. Считать нужные номера (множество need).
2. Считать M друзей и хранить для каждого имя и множество номеров.
3. Для каждого друга проверить: есть ли у него номер из need, которого нет у всех остальных?
4. Если да — он критически важен.
5. Вывести имена таких друзей в алфавитном порядке или '-'.
'''

# Считываем первую строку и разбиваем её на отдельные номера
# Если строка пустая — split() вернёт пустой список, set() сделает пустое множество
need = set(input().split())

# Считываем количество друзей
n = int(input())

# Словарь: имя друга -> множество номеров, которые у него есть
offers = {}

# Читаем информацию о M друзьях
for i in range(n):
    # Разделяем строку по ': ' — ожидается формат "Имя: номера"
    s = input().split(': ')
    name = s[0]  # Имя — всегда первая часть

    # Проверяем, есть ли что-то после двоеточия
    if len(s) > 1:
        # Если есть — разбиваем правую часть и создаём множество номеров
        offers[name] = set(s[1].split())
    else:
        # Если нет — у друга нет номеров
        offers[name] = set()

# Список для хранения имён критически важных друзей
result = []

# Перебираем каждого друга
for name in offers:
    # Создаём копию списка всех имён, чтобы убрать текущего
    copy = list(offers.keys()).copy()
    copy.remove(name)  # Теперь в copy — все друзья, кроме текущего

    # Находим номера, которые есть у текущего друга И входят в need
    num = offers[name] & need  # Пересечение: нужные номера у этого друга

    # Создаём множество всех номеров, которые есть у других друзей
    other = set()
    for guy in copy:
        other |= offers[guy]  # Объединяем (OR) все множества номеров остальных

    # Проверяем: есть ли у текущего друга нужные номера, которых нет у других?
    # Если num НЕ является подмножеством other — значит, есть уникальные номера
    if not num.issubset(other):
        result.append(name)

# Если нашлись критически важные друзья — выводим их в алфавитном порядке
if result:
    print(*sorted(result), sep='\n')
else:
    # Иначе выводим '-'
    print('-')
