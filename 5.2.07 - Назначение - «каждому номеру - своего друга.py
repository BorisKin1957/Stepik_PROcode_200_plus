'''
Задача: назначить каждому номеру из входного списка "друга",
у которого этот номер есть, и вывести пары "номер -> Имя"
в порядке возрастания номеров.

Если не все номера можно покрыть — вывести только те, что удалось назначить.
'''

# Шаг 1: Считываем строку с нужными номерами и преобразуем в множество
# Это позволяет автоматически убрать дубликаты и удобно проверять наличие
need = set(input().split())

# Шаг 2: Считываем количество друзей M
n = int(input())

# Список для хранения информации о каждом друге: (имя, множество его номеров)
offers = []

# Шаг 3: Читаем M строк формата "Имя: номер1 номер2 ..."
for i in range(n):
    # Разделяем строку по шаблону ': ' — ожидается ровно одно двоеточие с пробелом
    s = input().split(': ')
    name = s[0]  # Первая часть — имя друга

    # Проверяем, есть ли часть после двоеточия (т.е. есть ли номера)
    if len(s) > 1:
        # Если есть — разбиваем строку с номерами и создаём множество
        st = set(s[1].split())
    else:
        # Если нет — у друга нет номеров (пустое множество)
        st = set()

    # Добавляем кортеж (имя, множество номеров) в список offers
    offers.append((name, st))

# accum — множество уже "покрытых" (назначенных) номеров
accum = set()
# result — список назначенных групп: (имя, отсортированный список номеров)
result = []

# Проходим по каждому другу по порядку
for i in range(n):
    name, st = offers[i]  # Извлекаем имя и множество номеров друга
    vol = st & need  # Находим пересечение: номера, которые нужны и есть у друга
    accum |= vol  # Добавляем эти номера в общее покрытие (объединение множеств)

    # Если у друга есть нужные номера — добавляем его в результат
    if vol:
        # Преобразуем номера в целые числа, сортируем — для корректного вывода
        result.append((name, sorted([int(num) for num in vol])))

    # Если все нужные номера уже назначены — можно завершить цикл досрочно
    if accum == need:
        break

# Если удалось назначить хотя бы один номер
if result:
    # Список для хранения всех пар (номер, имя) — чтобы отсортировать по номеру
    pairs = []
    for name, lst in result:
        for num in lst:
            # Добавляем каждую пару "номер -> имя"
            pairs.append((num, name))

    # Сортируем все пары по номеру (по возрастанию)
    pairs.sort()

    # Выводим каждую пару в требуемом формате
    for num, name in pairs:
        print(f'{num} -> {name}')