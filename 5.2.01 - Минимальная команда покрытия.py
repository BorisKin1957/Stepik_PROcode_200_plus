'''
 История
В твоём списке желанных наклеек -- целая мини-коллекция, а времени на встречи совсем немного.
Одноклассники обещают помочь, каждый со своим набором «имею».
Хочется собрать маленькую «команду мечты», которая закроет весь твой need без лишних встреч.
Но есть подвох: если вариантов несколько, нужно выбрать самый «алфавитно ранний» состав.
И пусть победит здравый смысл, а не хаотичные сборы всей параллели!

🎯 Задание
Шаг 1. Считай строку с твоими нужными номерами need -- числа через пробел.
Повторы игнорируются по смыслу множества.
Шаг 2. Считай целое M -- число друзей.
Шаг 3. Считай M строк формата Имя: номера-имею (номера через пробел, строка может быть пустой).
Шаг 4. Найди минимальный по размеру набор имён, у которого объединение их «имею» содержит весь need.
Шаг 5. Если таких наборов несколько, выбери лексикографически минимальный по кортежу имён.
Шаг 6. Выведи выбранные имена по одному на строке в порядке этого кортежа.

Ограничения: M ≤ 20. Гарантируется, что решение существует.

🧪 Пример ввод

2 4 7 8
3
Лена: 1 2 9
Игорь: 4 5 7 8
Ася: 3 4 7


🧪 Пример вывод

Игорь
Лена
'''

# Импортируем функцию combinations из модуля itertools — она позволяет генерировать все возможные комбинации элементов заданной длины
from itertools import combinations as cb

# Считываем строку с нужными номерами, разбиваем по пробелам и преобразуем в множество целых чисел
# Множество автоматически убирает дубликаты
needed = set(map(int, input().split()))

# Создаём пустой словарь, где ключ — имя друга, значение — список (или множество) наклеек, которые у него есть и которые нам нужны
base = {}

# Считываем количество друзей M
for _ in range(int(input())):
    # Считываем строку в формате "Имя: номера", разделяем по двоеточию
    name, s = input().split(':')
    # Разбиваем строку с номерами, преобразуем в множество целых чисел
    # Пересекаем с `needed`, чтобы хранить только те наклейки, которые нам действительно нужны
    have = set(map(int, s.split())) & needed
    # Сохраняем в словарь: имя -> отсортированный список нужных наклеек у этого друга
    # Сортировка здесь не влияет на логику, но может быть для порядка (хотя дальше используется только ключ)
    base[name] = sorted(have)

# Сортируем словарь по ключам (именам) в алфавитном порядке
# Это важно: так мы гарантируем, что при переборе комбинаций имена будут в лексикографическом порядке
sorted_base = dict(sorted(base.items(), key=lambda x: x[0]))

# Перебираем возможные размеры команды — от 1 до M
# Начинаем с самых маленьких команд, чтобы найти минимальную по размеру
for i in range(len(sorted_base)):
    # Генерируем все возможные комбинации имён длины i+1 (от 1 до M)
    names = list(cb(sorted_base, i + 1))
    # Перебираем каждую комбинацию
    for j in range(len(names)):
        res = set()  # Множество для объединения наклеек текущей команды
        result = names[j]  # Текущая комбинация имён
        # Перебираем имена в комбинации
        for k in range(len(result)):
            # Добавляем все наклейки этого друга к общему набору (объединение множеств)
            res |= set(sorted_base[result[k]])
        # Проверяем, покрывает ли текущая команда все нужные наклейки
        if res == needed:
            # Выводим имена по одному на строке (в порядке кортежа)
            print(*result, sep='\n')
            # Завершаем программу — так как мы ищем минимальную команду,
            # и перебираем по возрастанию размера, первое найденное решение — оптимальное
            exit()