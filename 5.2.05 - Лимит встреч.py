'''
Шаг 1. Считай одну строку need --> это номера, разделённые пробелами.
Номера могут повторяться, но повторы нужно игнорировать (считаем need множеством).

Шаг 2. Считай целое число K --> сколько друзей максимум можно выбрать.

Шаг 3. Считай целое число M --> сколько друзей описано далее.

Шаг 4. Считай M строк вида:
Имя: номера
После двоеточия идут целые числа через пробел. Часть после двоеточия может быть
пустой, тогда считаем, что у этого друга нет номеров.

Шаг 5. Нужно выбрать набор из не более чем K друзей. Для выбранного набора
считаем покрытие так:
берём объединение всех номеров «имею» у выбранных друзей и оставляем только те
номера, которые входят в need.
Требуется максимизировать количество покрытых номеров.

Если максимальное покрытие можно получить разными наборами, применяй правила
выбора по порядку:
сначала выбирай набор с минимальным числом друзей,
если и таких вариантов несколько, выбери тот, у которого список имён,
отсортированный по алфавиту, лексикографически минимален.

Шаг 6. Выведи имена выбранных друзей по одному на строке. Печатай их в том порядке,
в котором эти друзья встречались во входных M строках.

Шаг 7. На следующей строке выведи покрытые номера из need по возрастанию через пробел.
Если покрытых номеров нет, выведи пустую строку после списка имён.

🧪 Пример 1 ввод

2 4 7 8
2
3
Лена: 1 2 9
Игорь: 4 5 7 8
Ася: 3 4 7


🧪 Пример 1 вывод

Лена
Игорь
'''

# Импортируем функцию combinations из модуля itertools — она поможет генерировать все возможные комбинации друзей по K человек
from itertools import combinations as cb

# Считываем строку с нужными номерами, разбиваем по пробелам и сохраняем как множество (дубликаты уйдут автоматически)
need = set(input().split())

# Считываем K — максимальное количество друзей, которых можно выбрать
k = int(input())

# Считываем M — количество описаний друзей
m = int(input())

# Словарь для хранения информации: имя -> множество номеров, которые у него есть
offers = {}

# Цикл по M строкам — читаем данные о каждом друге
for _ in range(m):
    # Разделяем строку по ": " — ожидаем формат "Имя: номера"
    s = input().split(': ')
    name = s[0]  # Имя — первая часть до двоеточия
    try:
        # Если после двоеточия что-то есть, разбиваем и сохраняем как множество
        have = set(s[1].split())
    except IndexError:
        # Если после двоеточия ничего нет (например, "Имя:"), создаём пустое множество
        have = set()
    # Сохраняем в словарь: имя -> множество номеров
    offers[name] = have

# Получаем все имена друзей (ключи словаря)
names = offers.keys()

# Словарь для хранения всех возможных комбинаций (наборов друзей) и покрытых ими номеров
variants = {}

# Перебираем все возможные размеры команды: от 1 до K включительно
for i in range(1, k + 1):
    # Генерируем все комбинации из names по i человек
    comp_names = tuple(cb(names, r=i))
    # Перебираем каждую комбинацию
    for comp in comp_names:
        vol = set()  # Множество для хранения покрытых номеров этой комбинацией
        # Перебираем каждого друга в текущей комбинации
        for j in range(len(comp)):
            tmp = offers[comp[j]]  # Получаем номера, которые есть у этого друга
            tmp &= need  # Оставляем только те номера, которые входят в need
            vol |= tmp  # Добавляем их в общее покрытие (объединение множеств)
        # Проверяем, покрыли ли мы все нужные номера
        if vol == need:
            # Если да — выводим имена по одному на строке
            print(*comp, sep='\n')
            # Выводим покрытые номера по возрастанию (сортируем как числа)
            print(*sorted(vol))
            # Завершаем программу — мы нашли идеальное покрытие
            exit()
        else:
            # Если не покрыли всё — сохраняем эту комбинацию и покрытые номера
            # Преобразуем номера в целые и сортируем
            variants[comp] = sorted([int(num) for num in vol])

# Сортируем все варианты по двум критериям:
# 1. По убыванию длины покрытия (максимизируем количество покрытых номеров)
# 2. По лексикографическому порядку имён (в кортеже имён)
result = sorted(variants.items(), key=lambda x: (-len(x[1]), x[0]))

# Выводим имена из лучшего варианта
# Если в кортеже одно имя — просто выводим его
# Иначе — выводим каждое имя на отдельной строке
if len(result[0][0]) == 1:
    print(result[0][0][0])
else:
    print(*result[0][0], sep='\n')

# Выводим покрытые номера (уже отсортированные)
print(*result[0][1])