'''
Задание
Что читаем

Целое Q.

Ровно Q строк-команд. Форматы команд (все заглавными):

VOTE user option

REVOKE user

COUNT option

TOP K

Ограничения на токены

user и option -- непустые строки без пробелов, чувствительны к регистру;
option может быть эмодзи.

K -- целое >= 1.

Смысл и поведение команд

VOTE user option → пользователь голосует за вариант.

Если у пользователя не было голоса: фиксируем, счётчик варианта +1.

Если уже голосовал за другой вариант: у старого варианта −1, у нового +1.

Если повторно голосует за тот же вариант: состояние не меняется.

Вывод: OK.

REVOKE user → отмена голоса пользователя.

Если пользователь голосовал: у его варианта −1, пользователь становится «без голоса».

Если не голосовал: вывод ERROR not-voted.

Иначе: OK.

COUNT option → вывести текущее число голосов за option (целое).

Если вариант ещё не встречался, считать 0.

TOP K → вывести до K лучших вариантов в формате option:count.

В зачёт берутся только варианты с count > 0.

Сортировка: по убыванию count, при равенстве -- лексикографически по option.

Если положительных вариантов меньше K, печатаем сколько есть.

Если нет ни одного положительного варианта -- вывести одиночную строку -.

Что печатаем

На каждую команду -- ровно одну строку результата.

VOTE / REVOKE → OK или ERROR not-voted.

COUNT → число.

TOP → список строк option:count (по одной на строку) либо -.

Обязательные структуры данных
Держим две мапы:

user → option (у кого какой голос сейчас),

option → count (сколько голосов у варианта).

Тонкости для однозначности

У пользователя одновременно ровно один активный голос или ни одного.

Счётчики не могут уходить в минус.

Для TOP нулевые варианты не показываем (но для COUNT их значение равно 0).

Сравнение вариантов при тай-брейке -- обычное лексикографическое сравнение строк.

🧪 Пример 1 — ввод

7
VOTE u1 🐍
COUNT 🐍
VOTE u2 🐍
VOTE u1 🐧
COUNT 🐍
COUNT 🐧
TOP 2


🧪 Пример 1 — вывод

OK
1
OK
OK
1
1
🐍:1
🐧:1
'''

# Инициализация словарей:
# users — хранит, за какой вариант голосует каждый пользователь: user → option
# options — хранит количество голосов за каждый вариант: option → count
users = {}
options = {}

# Считываем количество команд Q
for _ in range(int(input())):
    s = input().split()  # Разбиваем строку на части: команда, аргументы

    # === КОМАНДА VOTE: пользователь голосует за вариант ===
    if s[0] == 'VOTE':
        user, opt = s[1], s[2]  # Извлекаем имя пользователя и вариант

        # Проверяем, голосовал ли пользователь ранее
        if user in users:
            # Если он уже голосовал за ДРУГОЙ вариант
            if users[user] != opt:
                old_opt = users[user]  # Запоминаем старый вариант
                options[old_opt] -= 1  # Уменьшаем счётчик старого варианта
                # Не удаляем старый вариант из options, даже если стало 0!
                # Просто оставляем его со значением 0 — это важно для COUNT
                users[user] = opt  # Обновляем голос пользователя
                options[opt] = options.get(opt, 0) + 1  # Увеличиваем счётчик нового варианта
            # Если голосует за тот же самый вариант — ничего не делаем
            # (состояние не меняется)
        else:
            # Пользователь голосует впервые
            users[user] = opt  # Запоминаем его выбор
            options[opt] = options.get(opt, 0) + 1  # Увеличиваем счётчик

        print('OK')  # Всегда выводим OK при успешном VOTE

    # === КОМАНДА REVOKE: отмена голоса пользователя ===
    elif s[0] == 'REVOKE':
        user = s[1]  # Извлекаем имя пользователя

        # Если пользователь не голосовал — ошибка
        if user not in users:
            print('ERROR not-voted')
        else:
            # Получаем вариант, за который он голосовал
            voted_option = users[user]
            # Уменьшаем счётчик этого варианта
            options[voted_option] -= 1
            # Не удаляем ключ из options! Он может стать 0, но должен остаться
            # Удаляем пользователя из списка проголосовавших
            del users[user]
            print('OK')

    # === КОМАНДА COUNT: вывести число голосов за вариант ===
    elif s[0] == 'COUNT':
        opt = s[1]  # Извлекаем вариант
        # Если вариант ещё не встречался — 0 голосов
        # Используем get, чтобы безопасно получить значение
        print(options.get(opt, 0))

    # === КОМАНДА TOP K: вывести до K лучших вариантов ===
    elif s[0] == 'TOP':
        k = int(s[1])  # Сколько вариантов нужно вывести
        # Фильтруем только те варианты, у которых count > 0
        positive_options = [(opt, cnt) for opt, cnt in options.items() if cnt > 0]

        # Сортируем: по убыванию count, при равенстве — лексикографически по имени
        positive_options.sort(key=lambda x: (-x[1], x[0]))

        # Если нет ни одного варианта с положительным счётом
        if not positive_options:
            print('-')
        else:
            # Берём не более чем k первых элементов
            for opt, cnt in positive_options[:k]:
                print(f'{opt}:{cnt}')
