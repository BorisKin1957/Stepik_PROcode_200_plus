'''
Задание
Вход

Строка need -- нужные номера (через пробел; порядок не важен).

Целое L -- максимум друзей, которых можно встретить за один день.

Целое M.

Далее M строк в формате Имя: имею -- после двоеточия перечислены номера через
пробел (может быть пусто).

Что нужно сделать

Выбрать некоторый набор друзей S, чтобы объединение их множеств «имею» покрывало
все номера из need.

Разбить выбранных друзей S по дням, чтобы в каждом дне было не более L человек
(каждый друг используется не более одного раза).

Минимизировать число дней d.

Вывод

Сначала выведи минимальное число дней d.

Затем выведи один корректный план раскладки по дням (дни нумеруются с 1):

Day 1: Имя Имя ...
Day 2: Имя Имя ...
...


Внутри дня имена отсортированные по алфавиту. Пустые дни не печатай.

Если решения нет -- выведи Пусто.

🔍 Что не так с текущим решением?
Текущий код не решает задачу корректно, потому что:

Он перебирает комбинации по L друзей, но не перебирает все возможные наборы друзей, а просто идёт по порядку.
Он не минимизирует количество дней — он просто строит жадное покрытие, используя комбинации подряд.
Он может пропустить оптимальное решение.
✅ Как правильно решить?
Для корректного решения нужно:

Найти все возможные подмножества друзей, которые покрывают need.
Для каждого такого подмножества проверить, можно ли разбить его на группы по L человек (т.е. ceil(|S| / L) дней).
Выбрать подмножество с минимальным числом дней.
Это — задача минимизации покрытия множества, и для точного решения обычно используют:

Перебор с возвратом (backtracking),
Или динамическое программирование по подмножествам (если len(need) мало),
Или целочисленное линейное программирование.
Если нужно — могу предложить полностью переписанное корректное решение.
'''

from itertools import combinations as cb

need = set(input().split())
l, m = int(input()), int(input())
offers = {}

for _ in range(m):
    s = input().split(':')
    name = s[0]
    if len(s) > 1:
        offers[name] = set(s[1].strip().split())
    else:
        offers[name] = set()

names = []


pairs = cb(sorted(offers.keys()), r=l)
day = 1
total_vol = set()
result = {}

for pair in pairs:
    key = []
    for i in range(l):
        if pair[i] not in names:
            names.append(pair[i])
            owner_vol = offers[pair[i]] & need
            if owner_vol:
                total_vol |= owner_vol
                key.append(pair[i])

    if key:
        result[day] = sorted(key)
    day += 1
    if total_vol == need:
        break
if result:
    print(len(result))
    for day, names in result.items():
        print(f'Day {day}: {' '.join(names)}')
else:
    print('Пусто')