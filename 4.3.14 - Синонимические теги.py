'''
Задание:
Дано p пар синонимичных тегов, затем n постов с тегами.
Нужно:
1. Построить граф синонимов (неориентированный).
2. Найти компоненты связности.
3. Для каждой компоненты выбрать лексикографически минимальный тег как "имя".
4. В каждом посте заменить все теги на имена их компонент.
5. Удалить дубликаты в каждом посте (работать с множеством).
6. Посчитать, сколько раз каждый нормализованный тег встречается в постах.
7. Вывести результат в формате tag:count по алфавиту. Если нет тегов — вывести '-'.
'''

# Считываем количество пар синонимов
p = int(input())

# Читаем p строк, каждая содержит два тега — синонимы
# Каждую строку разбиваем на слова, убираем пробелы и сохраняем как список списков
L = [list(map(str.strip, input().split())) for _ in range(p)]

# Словарь для хранения соответствия: тег -> канонический тег (имя компоненты)
base = {}

# Обрабатываем список пар синонимов, объединяя их в компоненты связности
while L:
    n = len(L)  # текущее количество необработанных пар
    if n > 1:
        # Берём первую пару как начальную компоненту
        part = L[1:]  # оставшиеся пары
        st = set(L[0])  # множество тегов текущей компоненты
        del L[0]  # удаляем первую пару из списка

        # Проходим по оставшимся парам
        for i in range(n - 1):
            # Если текущая пара пересекается с нашей компонентой (есть общий тег)
            if st & set(part[i]):  # проверка пересечения множеств
                st |= set(part[i])  # объединяем множества (расширяем компоненту)
                # Удаляем эту пару из L, если она ещё там (чтобы не обрабатывать дважды)
                if part[i] in L:
                    L.remove(part[i])
    else:
        # Если осталась только одна пара
        st = set(L[0])
        del L[0]

    # Преобразуем множество тегов в отсортированный список
    tmp = list(st)
    tmp.sort()
    # Имя компоненты — лексикографически минимальный тег
    tag = tmp[0]

    # Все остальные теги в компоненте ссылаются на этот минимальный
    for word in tmp[1:]:
        base[word] = tag

# Теперь обрабатываем посты
result = {}  # счётчик: нормализованный_тег -> количество постов

n_posts = int(input())  # количество постов

for _ in range(n_posts):
    # Считываем теги поста, разбиваем на множество (удаляем дубли в одном посте)
    st = set(input().split())

    # Заменяем каждый тег на его каноническую форму:
    # если тег есть в base — берём base[word], иначе оставляем как есть
    new = {base.setdefault(word, word) for word in st}

    # Увеличиваем счётчик для каждого нормализованного тега в этом посте
    for tag in new:
        result[tag] = result.get(tag, 0) + 1

# Вывод результата
if result:
    # Сортируем по алфавиту по ключам (тегам)
    result = sorted(result.items())
    for k, v in result:
        print(f'{k}:{v}')
else:
    # Если ни одного тега не было
    print('-')