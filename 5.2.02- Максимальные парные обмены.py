'''
Шаг 1. Считай целое N -- число детей. Далее для каждого ребёнка три строки:

Имя
имею: <номера через пробел>
нужно: <номера через пробел>


Шаг 2. Построй неориентированный граф по именам: между A и B есть ребро,
если одновременно выполняется
(имею_A ∩ нужно_B ≠ ∅) и (имею_B ∩ нужно_A ≠ ∅).

Шаг 3. Найди максимальное паросочетание по людям в этом графе (каждый участвует
не более одного раза).

Шаг 4. Выведи найденные пары по одной строке в формате
Имя1 <-> Имя2
в лексикографическом порядке по Имя1, а при равенстве -- по Имя2. Если пар нет,
 вывода нет.

Замечание. Если существует несколько разных максимальных раскладок одной и той
же мощности, допустима любая, при этом порядок печати всё равно по правилу из шага 4.

🧪 Пример 1 ввод

3
Ася
имею: 1 4
нужно: 7
Игорь
имею: 7 8
нужно: 4
Лена
имею: 2
нужно: 9


🧪 Пример 1 вывод

Ася <-> Игорь
'''

'''
Цель программы: найти максимальное количество пар детей, которые могут обменяться предметами.
Условие пары: у одного есть то, что нужно другому, и наоборот.
'''

# Словари для хранения того, что каждый ребёнок "имеет" и "нуждается"
have_base = {}  # ключ — имя, значение — множество номеров предметов, которые есть у ребёнка
need_base = {}  # ключ — имя, значение — множество номеров предметов, которые нужны ребёнку

# Читаем количество детей
for _ in range(int(input())):
    name = input()  # Считываем имя ребёнка

    # Считываем строку "имею: ..." и разбиваем по ": "
    s = input().split(': ')
    # Берём часть после "имею:", разбиваем на отдельные номера и создаём множество
    have = set(s[1].split())
    # Сохраняем множество в словарь have_base по имени
    # Если имя уже есть (на случай дубликатов), оставляем старое значение
    have_base[name] = have_base.get(name, have)

    # Аналогично для строки "нужно: ..."
    s = input().split(': ')
    need = set(s[1].split())
    need_base[name] = need_base.get(name, need)

# Список для хранения найденных пар (как множеств из двух имён)
pairs = []
# Множество имён, уже участвующих в обмене (чтобы никто не участвовал дважды)
blocked = set()

# Перебираем всех детей: name_need — тот, кому что-то нужно
for name_need in need_base:
    # Перебираем всех детей: name_have — тот, у кого что-то есть
    for name_have in have_base:
        # Исключаем случай, когда ребёнок сравнивает себя с собой
        if name_need != name_have:
            # Проверяем, есть ли пересечение:
            # 1. То, что нужно name_need, есть у name_have
            # 2. То, что нужно name_have, есть у name_need
            if (need_base[name_need] & have_base[name_have]  # пересечение: у name_have есть то, что нужно name_need
                    and need_base[name_have] & have_base[name_need]  # и наоборот
                    and {name_have, name_need} not in pairs  # пара ещё не добавлена
                    and not {name_have, name_need} & blocked):  # ни один из них ещё не участвовал
                # Добавляем пару как множество (порядок не важен)
                pairs.append({name_have, name_need})
                # Добавляем обоих в "заблокированные" — они уже участвуют в обмене
                blocked |= {name_have, name_need}  # то же, что blocked.update(...)

# Список для финального результата в виде отсортированных пар
result = []

# Преобразуем каждую пару (множество) в отсортированный список [имя1, имя2], где имя1 < имя2
for pair in pairs:
    result.append(sorted(pair))

# Сортируем все пары:
# - сначала по первому имени (лексикографически)
# - при равенстве первого имени — по второму
result = sorted(result, key=lambda x: x[0])

# Если есть хотя бы одна пара — выводим
if result:
    for pair in result:
        print(f'{pair[0]} <-> {pair[1]}')