'''
Шаг 1. Считай строку с нужными номерами need это числа через пробел.
Повторы игнорируются по смыслу множества.
Шаг 2. Считай целое C это лимит назначений на одного друга.
Шаг 3. Считай целое M.
Шаг 4. Считай M строк формата Имя: имею это числа через пробел, строка может быть пустой.

Шаг 5. Назначь каждому номеру из need какого-то друга, у которого он есть,
так чтобы у каждого друга было не больше C назначений.
Шаг 6. Максимизируй число назначенных номеров.
Шаг 7. Выведи сначала число назначенных, затем пары номер -> Имя по возрастанию
номер (порядок имён не важен).
Если подходящих пар нет, выведи 0 и больше ничего.

Примечание. Допустима любая корректная раскладка с максимальным числом назначенных номеров.

🧪 Пример 1 ввод

2 4 7 8
1
3
Ася: 2 8
Игорь: 4 7
Лена: 7 8


🧪 Пример 1 вывод

3
2 -> Ася
4 -> Игорь
7 -> Лена
'''

'''
РЕАКЦИЯ ИИ:

Это не имеет смысла. Ты вычитаешь у Аси номера, которые есть у Игоря и Лены. 
Но по условию один и тот же номер может быть у нескольких друзей, и это нормально — 
нужно выбрать одного из них, чтобы назначить номер, но не удалять его у других.


Не максимизируется количество назначений. Ты теряешь номера, 
которые мог бы назначить, из-за этой вычитания.

Не учитывается, что один друг может взять до C номеров, 
но ты просто берёшь первые c из странного "остатка".

1 2 3
1
3
Ася: 1 2
Игорь: 2 3
Лена: 1 3
'''

need = set(input().split())
c = int(input())
n = int(input())

offers = []

for i in range(n):
    s = input().split(': ')
    name = s[0]
    if len(s) > 1:
        st = set(s[1].split())
        st &= need
    else:
        st = set()
    offers.append([name, st])


offers_new = []

for i in range(n):
    vol = offers[i][1]
    for j in range(i + 1, n):
        vol -= offers[j][1]
    offers_new.append([offers[i][0], sorted([int(num) for num in vol])[:c]])

pairs = []

for name, lst in offers_new:
    for num in lst:
        pairs.append((num, name))
if pairs:
    print(len(pairs))
    pairs.sort()
    for num, name in pairs:
        print(f'{num} -> {name}')
else:
    print(0)
