'''
Считай целое Q, затем Q строк команд из множества:

SET k v -- положить строковое значение v по ключу k. Если ключ уже был,
значение перезаписывается. Вывод: OK.

GET k -- вывести значение по ключу k или -1, если ключа нет.

DEL k -- удалить ключ k. Если ключа не было → ERROR not-found, иначе OK.

HAS k -- вывести YES, если ключ есть, иначе NO.

SIZE -- вывести текущее число ключей.

LIST prefix -- вывести все ключи, начинающиеся с prefix, в лексикографическом порядке,
через запятую без пробелов. Если таких нет → -.

Выводи ровно одну строку на каждую команду.
'''

# Создаём пустой словарь (базу данных "ключ-значение")
base = {}

# Считываем количество команд Q
for _ in range(int(input())):
    # Считываем команду и разбиваем на части по пробелам
    s = input().split()

    # Обрабатываем команду SET: устанавливает значение по ключу
    if s[0] == 'SET':
        k, v = s[1], s[2]  # Извлекаем ключ и значение
        base[k] = v        # Записываем значение в словарь по ключу
        print('OK')        # Выводим подтверждение

    # Обрабатываем команду GET: получает значение по ключу
    elif s[0] == 'GET':
        k = s[1]           # Извлекаем ключ
        # Получаем значение по ключу, если ключа нет — возвращаем -1
        print(base.get(k, -1))

    # Обрабатываем команду DEL: удаляет ключ
    elif s[0] == 'DEL':
        k = s[1]           # Извлекаем ключ
        if k in base:      # Проверяем, существует ли ключ
            del base[k]    # Удаляем ключ из словаря
            print('OK')    # Подтверждаем удаление
        else:
            print('ERROR not-found')  # Сообщаем, что ключ не найден

    # Обрабатываем команду HAS: проверяет наличие ключа
    elif s[0] == 'HAS':
        k = s[1]           # Извлекаем ключ
        # Выводим YES, если ключ есть, иначе NO
        print('YES' if k in base else 'NO')

    # Обрабатываем команду SIZE: выводит количество ключей
    elif s[0] == 'SIZE':
        print(len(base))   # Длина словаря = количество пар ключ-значение

    # Обрабатываем команду LIST: выводит все ключи с заданным префиксом
    elif s[0] == 'LIST':
        prefix = s[1]      # Извлекаем префикс
        # Формируем список всех ключей, которые начинаются с prefix, в отсортированном порядке
        lst = [k for k in sorted(base.keys()) if k.startswith(prefix)]
        # Выводим ключи через запятую без пробелов, или '-' если список пуст
        print(','.join(lst) if lst else '-')
